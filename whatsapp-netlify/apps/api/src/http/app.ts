import express from "express";
import cookieParser from "cookie-parser";
import helmet from "helmet";
import { randomUUID } from "node:crypto";
import { db } from "../config/db.js";
import { env } from "../config/env.js";
import { errorHandler, asyncRoute, AppError } from "./errors.js";
import { authenticate, requireOrigin } from "../middleware/auth.js";
import { authRoutes } from "../routes/auth.js";
import { contactRoutes } from "../routes/contacts.js";
import { segmentRoutes } from "../routes/segments.js";
import { templateRoutes } from "../routes/templates.js";
import { campaignRoutes } from "../routes/campaigns.js";
import { settingsRoutes } from "../routes/settings.js";
import { dashboardRoutes } from "../routes/dashboard.js";
import { webhookRoutes } from "../routes/webhook.js";
import { messageRoutes } from "../routes/messages.js";
export const app = express();
app.disable("x-powered-by");
app.use(helmet());
app.use((_req, res, next) => { res.locals.requestId = randomUUID(); res.set("X-Request-ID", res.locals.requestId as string).set("Cache-Control", "no-store"); next(); });
app.use("/api/webhooks/whatsapp", webhookRoutes);
app.use(cookieParser()); app.use(requireOrigin);
app.use(express.json({ limit: "256kb" }));
app.get("/api/health", asyncRoute(async (_req, res) => { await db.workspace.count({ take: 1 }); res.json({ ok: true, mode: env.DRY_RUN ? "simulacion" : "real" }); }));
app.use("/api/auth", authRoutes);
app.use("/api", authenticate);
app.use("/api/contacts", contactRoutes); app.use("/api/segments", segmentRoutes);
app.use("/api/templates", templateRoutes); app.use("/api/campaigns", campaignRoutes);
app.use("/api/settings", settingsRoutes); app.use("/api/dashboard", dashboardRoutes);
app.use("/api/messages", messageRoutes);
app.use((_req, _res, next) => next(new AppError(404, "La ruta solicitada no existe.", "NOT_FOUND")));
app.use(errorHandler);
